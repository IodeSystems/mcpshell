package toolkit_test

import "testing"

// Expectations are what Node prints for the same call (ICU en-US).
func TestNumberFormat(t *testing.T) {
	const two = `{minimumFractionDigits: 2, maximumFractionDigits: 2}`
	runCases(t, newCoreShell, []evalCase{
		{"exact sum two digits", `(0.1 + 0.2).toLocaleString("en-US", ` + two + `)`, "0.30"},
		{"default digits", `(1234567.891).toLocaleString()`, "1,234,567.891"},
		{"en-US explicit", `(1234567.891).toLocaleString("en-US")`, "1,234,567.891"},
		{"default max three", `(1.23456).toLocaleString()`, "1.235"},
		{"integer", `(1234567).toLocaleString()`, "1,234,567"},
		{"four digits group", `(1234).toLocaleString()`, "1,234"},
		{"zero", `(0).toLocaleString()`, "0"},
		{"negative", `(-1234.567).toLocaleString()`, "-1,234.567"},
		{"half rounds away", `(2.5).toLocaleString("en-US", {maximumFractionDigits: 0})`, "3"},
		{"negative half rounds away", `(-2.5).toLocaleString("en-US", {maximumFractionDigits: 0})`, "-3"},
		{"exact 1.005", `(1.005).toLocaleString("en-US", {maximumFractionDigits: 2})`, "1.01"},
		{"min digits pad", `(5).toLocaleString("en-US", {minimumFractionDigits: 2})`, "5.00"},
		{"min digits raises max", `(5.12345).toLocaleString("en-US", {minimumFractionDigits: 4})`, "5.1235"},
		{"max digits only", `(5.5).toLocaleString("en-US", {maximumFractionDigits: 0})`, "6"},
		{"big integer exact", `(2 ** 80).toLocaleString()`, "1,208,925,819,614,629,174,706,176"},
		{"big decimal exact", `(12345678901234567890.12).toLocaleString("en-US", ` + two + `)`, "12,345,678,901,234,567,890.12"},
		{"currency usd", `(1234.5).toLocaleString("en-US", {style: "currency", currency: "USD"})`, "$1,234.50"},
		{"currency negative", `(-1234.5).toLocaleString("en-US", {style: "currency", currency: "USD"})`, "-$1,234.50"},
		{"currency eur", `(1234.5).toLocaleString("en-US", {style: "currency", currency: "EUR"})`, "€1,234.50"},
		{"currency jpy", `(1234.5).toLocaleString("en-US", {style: "currency", currency: "JPY"})`, "¥1,235"},
		{"currency code display", `(1234.5).toLocaleString("en-US", {style: "currency", currency: "USD", currencyDisplay: "code"})`, "USD 1,234.50"},
		{"currency without symbol", `(1234.5).toLocaleString("en-US", {style: "currency", currency: "CHF"})`, "CHF 1,234.50"},
		{"currency fraction override", `(1234.5).toLocaleString("en-US", {style: "currency", currency: "USD", maximumFractionDigits: 0})`, "$1,235"},
		{"currency exact", `(0.1 + 0.2).toLocaleString("en-US", {style: "currency", currency: "USD"})`, "$0.30"},
		{"percent", `(0.256).toLocaleString("en-US", {style: "percent"})`, "26%"},
		{"percent digits", `(0.256).toLocaleString("en-US", {style: "percent", maximumFractionDigits: 1})`, "25.6%"},
		{"percent min", `(0.5).toLocaleString("en-US", {style: "percent", minimumFractionDigits: 1})`, "50.0%"},
		{"percent large", `(12.5).toLocaleString("en-US", {style: "percent"})`, "1,250%"},
		{"compact thousand", `(1500).toLocaleString("en-US", {notation: "compact"})`, "1.5K"},
		{"compact 1234", `(1234).toLocaleString("en-US", {notation: "compact"})`, "1.2K"},
		{"compact million", `(1234567).toLocaleString("en-US", {notation: "compact"})`, "1.2M"},
		{"compact 12345", `(12345).toLocaleString("en-US", {notation: "compact"})`, "12K"},
		{"compact 999999", `(999999).toLocaleString("en-US", {notation: "compact"})`, "1M"},
		{"compact small", `(999).toLocaleString("en-US", {notation: "compact"})`, "999"},
		{"compact billion", `(2500000000).toLocaleString("en-US", {notation: "compact"})`, "2.5B"},
		{"compact fraction", `(1.234).toLocaleString("en-US", {notation: "compact"})`, "1.2"},
		{"integer digits", `(5).toLocaleString("en-US", {minimumIntegerDigits: 2})`, "05"},
		{"significant", `(1234.5678).toLocaleString("en-US", {maximumSignificantDigits: 3})`, "1,230"},
		{"significant small", `(0.000123456).toLocaleString("en-US", {maximumSignificantDigits: 2})`, "0.00012"},
		{"min significant", `(5).toLocaleString("en-US", {minimumSignificantDigits: 3})`, "5.00"},
		{"no grouping", `(1000000).toLocaleString("en-US", {useGrouping: false})`, "1000000"},
		{"sign always", `(5).toLocaleString("en-US", {signDisplay: "always"})`, "+5"},
		{"sign except zero", `(0).toLocaleString("en-US", {signDisplay: "exceptZero"})`, "0"},
		{"negative rounds to negative zero", `(-0.001).toLocaleString("en-US", {maximumFractionDigits: 0})`, "-0"},
		{"NaN", `NaN.toLocaleString()`, "NaN"},
		{"infinity", `Infinity.toLocaleString()`, "∞"},
		{"Intl.NumberFormat new", `new Intl.NumberFormat("en-US", {style: "currency", currency: "USD"}).format(1234.5)`, "$1,234.50"},
		{"Intl.NumberFormat call", `Intl.NumberFormat("en-US").format(1234567.891)`, "1,234,567.891"},
		{"Intl.NumberFormat reused", `let f = new Intl.NumberFormat("en-US", ` + two + `); [f.format(1), f.format(0.255)]`, `["1.00", "0.26"]`},
		{"Intl.NumberFormat numeric string", `new Intl.NumberFormat().format("1234.5")`, "1,234.5"},
		{"sqrt uses shortest decimal", `(2 ** 0.5).toLocaleString("en-US", {maximumFractionDigits: 5})`, "1.41421"},
	})
	runErrors(t, newCoreShell, []evalCase{
		{"locale", `(1).toLocaleString("de-DE")`, `only "en-US"`},
		{"unit style", `(1).toLocaleString("en-US", {style: "unit"})`, `style "unit"`},
		{"unknown option", `(1).toLocaleString("en-US", {roundingMode: "floor"})`, "roundingMode is not supported"},
		{"currency missing", `(1).toLocaleString("en-US", {style: "currency"})`, "needs a currency code"},
		{"currency without style", `(1).toLocaleString("en-US", {currency: "USD"})`, `needs style "currency"`},
		{"scientific", `(1).toLocaleString("en-US", {notation: "scientific"})`, "not supported"},
		{"digits range", `(1).toLocaleString("en-US", {minimumFractionDigits: 3, maximumFractionDigits: 2})`, "greater than"},
		{"bad value", `(1).toLocaleString("en-US", {style: "money"})`, "option style must be one of"},
		{"currency name", `(1).toLocaleString("en-US", {style: "currency", currency: "USD", currencyDisplay: "name"})`, "not supported"},
		{"extra arg", `(1).toLocaleString("en-US", {}, 3)`, "at most 2"},
		{"format of non-number", `new Intl.NumberFormat().format({})`, "number"},
		{"constructor locale", `new Intl.NumberFormat("fr-FR")`, `only "en-US"`},
	})
}

func TestToMarkdown(t *testing.T) {
	runCases(t, newCoreShell, []evalCase{
		{"objects", `toMarkdown([{name: "ann", n: 3}, {name: "bo", n: 12}])`,
			"| name | n |\n| --- | ---: |\n| ann | 3 |\n| bo | 12 |"},
		{"pipe", `[{a: 1}] |> toMarkdown()`, "| a |\n| ---: |\n| 1 |"},
		{"first-seen column order", `toMarkdown([{a: 1, b: 2}, {c: 3, a: 4}])`,
			"| a | b | c |\n| ---: | ---: | ---: |\n| 1 | 2 |  |\n| 4 |  | 3 |"},
		{"columns pick and order", `toMarkdown([{a: 1, b: "x", c: 3}], {columns: ["b", "a"]})`,
			"| b | a |\n| --- | ---: |\n| x | 1 |"},
		{"columns missing key is empty", `toMarkdown([{a: 1}], {columns: ["a", "z"]})`,
			"| a | z |\n| ---: | --- |\n| 1 |  |"},
		{"pipe escaped", `toMarkdown([{t: "a|b"}])`, "| t |\n| --- |\n| a\\|b |"},
		{"header escaped", `toMarkdown([{"a|b": 1}])`, "| a\\|b |\n| ---: |\n| 1 |"},
		{"newline", `toMarkdown([{t: "a\nb"}])`, "| t |\n| --- |\n| a<br>b |"},
		{"null empty", `toMarkdown([{a: null, b: 1}])`, "| a | b |\n| --- | ---: |\n|  | 1 |"},
		{"mixed column left", `toMarkdown([{a: 1}, {a: "x"}])`, "| a |\n| --- |\n| 1 |\n| x |"},
		{"null and numbers right", `toMarkdown([{a: 1}, {a: null}])`, "| a |\n| ---: |\n| 1 |\n|  |"},
		{"exact numbers", `toMarkdown([{a: 0.1 + 0.2}])`, "| a |\n| ---: |\n| 0.3 |"},
		{"booleans", `toMarkdown([{a: true}])`, "| a |\n| --- |\n| true |"},
		{"nested value is json", `toMarkdown([{a: [1, 2], b: {x: 1}}])`, "| a | b |\n| --- | --- |\n| [1,2] | {\"x\":1} |"},
		{"date cell", `toMarkdown([{d: new Date(0)}])`, "| d |\n| --- |\n| 1970-01-01T00:00:00.000Z |"},
		{"arrays header true", `toMarkdown([["a", "b"], [1, "x"], [22, "y"]], {header: true})`,
			"| a | b |\n| ---: | --- |\n| 1 | x |\n| 22 | y |"},
		{"arrays header names", `toMarkdown([[1, 2]], {header: ["x", "y"]})`, "| x | y |\n| ---: | ---: |\n| 1 | 2 |"},
		{"arrays short row", `toMarkdown([[1]], {header: ["x", "y"]})`, "| x | y |\n| ---: | --- |\n| 1 |  |"},
		{"empty", `toMarkdown([])`, ""},
		{"empty with columns", `toMarkdown([], {columns: ["a"]})`, "| a |\n| --- |"},
	})
	runErrors(t, newCoreShell, []evalCase{
		{"not an array", `toMarkdown({a: 1})`, "array"},
		{"arrays need header", `toMarkdown([[1, 2]])`, "needs a header"},
		{"mixed rows", `toMarkdown([{a: 1}, 2])`, "row 1"},
		{"unknown option", `toMarkdown([{a: 1}], {colums: ["a"]})`, `"colums" is not supported`},
		{"wide row", `toMarkdown([[1, 2, 3]], {header: ["a"]})`, "3 cells"},
		{"header on objects", `toMarkdown([{a: 1}], {header: true})`, "array of arrays"},
		{"extra arg", `toMarkdown([], {}, 1)`, "takes 2 argument"},
	})
}
